#!/usr/bin/env python
"""
Leave-Rule-Out cross-validation -- the harder, more honest generalization
test the earlier overfitting diagnosis was missing.

The production split (make_context_splits, grouped by context_id) never
splits a *context* across train/val/test, but every context -- train AND
test alike -- is still generated by one of only 7-12 source_rule_id
generation rules per specialist. So the "held-out" test set was always
drawn from generation logic the model had already seen thousands of rows
of; it was testing interpolation within a known rule, not extrapolation to
an unseen one.

This script groups by source_rule_id instead: GroupKFold with
n_splits = number of distinct rules in that specialist, i.e. true
leave-one-rule-out (LORO). Each fold trains on every rule except one and
tests on the single held-out rule's rows in full -- the model has never
seen anything generated by that rule's logic. This is a real,
uncomfortable test, and it is reported as-is, whatever it shows.

Usage: .venv/Scripts/python.exe scripts/experiments/leave_rule_out_cv.py
"""
from __future__ import annotations

import sys
import time
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge
from sklearn.model_selection import GroupKFold

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from train_specialists import EXCLUDED_COLUMNS_V7, DATA_VERSION_CONFIG, detect_schema, regression_metrics  # noqa: E402
from overfitting_diagnosis import build_preprocessor  # noqa: E402

TARGET = "shelf_life_days"
CATEGORIES = ["soft", "semi_hard", "hard"]
TASKS = ["general_shelf_life", "safety_endpoint"]
SEED = 42
OUT_DIR = Path(__file__).resolve().parent / "overfitting_diagnosis"
OUT_DIR.mkdir(parents=True, exist_ok=True)


def load_category_df(category: str) -> pd.DataFrame:
    filename = DATA_VERSION_CONFIG["v7"]["csv_pattern"].format(CAT=category.upper())
    return pd.read_csv(ROOT / "data" / "raw" / filename)


def lgbm_factory():
    import lightgbm as lgb
    return lgb.LGBMRegressor(
        n_estimators=400, learning_rate=0.03, num_leaves=31, min_child_samples=20,
        subsample=0.9, colsample_bytree=0.9, random_state=SEED, n_jobs=-1, verbose=-1,
    )


def ridge_factory():
    return Ridge(alpha=1.0, random_state=SEED)


def run_loro(task_df: pd.DataFrame, exclude: list[str], model_name: str, factory) -> dict:
    dynamic_exclude = [c for c in task_df.columns if c != TARGET and c not in exclude and task_df[c].isna().all()]
    schema = detect_schema(task_df, TARGET, exclude=exclude + dynamic_exclude)
    numeric_cols = schema["numeric"] + schema["binary"]
    categorical_cols = schema["categorical"]
    cols = numeric_cols + categorical_cols
    y = task_df[TARGET].to_numpy(dtype=float)
    rules = task_df["source_rule_id"].to_numpy()
    n_rules = task_df["source_rule_id"].nunique()

    gkf = GroupKFold(n_splits=n_rules)
    per_rule = []
    for tr_idx, te_idx in gkf.split(task_df[cols], y, groups=rules):
        held_out_rule = task_df.iloc[te_idx]["source_rule_id"].iat[0]
        pre = build_preprocessor(numeric_cols, categorical_cols)
        X_tr = pre.fit_transform(task_df.iloc[tr_idx][cols])
        X_te = pre.transform(task_df.iloc[te_idx][cols])
        model = factory()
        model.fit(X_tr, y[tr_idx])
        pred = model.predict(X_te)
        m = regression_metrics(y[te_idx], pred)
        per_rule.append({"held_out_rule": held_out_rule, "n_test_rows": len(te_idx), "r2": m["r2"], "mae": m["mae"], "rmse": m["rmse"]})

    r2_values = [r["r2"] for r in per_rule]
    return {
        "model": model_name, "n_rules": n_rules,
        "mean_r2": float(np.mean(r2_values)), "median_r2": float(np.median(r2_values)),
        "std_r2": float(np.std(r2_values)), "min_r2": float(np.min(r2_values)), "max_r2": float(np.max(r2_values)),
        "per_rule": per_rule,
    }


def main():
    t_start = time.time()
    all_results = []
    for category in CATEGORIES:
        df = load_category_df(category)
        for task in TASKS:
            task_df = df[df["model_task"] == task].reset_index(drop=True)
            label = f"{category}/{task}"
            print(f"\n{'=' * 78}\n{label}  (n={len(task_df)}, n_rules={task_df['source_rule_id'].nunique()})\n{'=' * 78}")
            for model_name, factory in (("ridge_regression", ridge_factory), ("lightgbm_production_hparams", lgbm_factory)):
                res = run_loro(task_df, EXCLUDED_COLUMNS_V7, model_name, factory)
                res.update({"category": category, "task": task})
                all_results.append(res)
                print(f"  {model_name}: mean_r2={res['mean_r2']:.3f}  median={res['median_r2']:.3f}  "
                      f"std={res['std_r2']:.3f}  range=[{res['min_r2']:.3f}, {res['max_r2']:.3f}]")
                for r in res["per_rule"]:
                    print(f"      held out {r['held_out_rule']:55s} n={r['n_test_rows']:4d}  r2={r['r2']:7.3f}  mae={r['mae']:6.2f}")

    summary_rows = [{k: v for k, v in r.items() if k != "per_rule"} for r in all_results]
    pd.DataFrame(summary_rows).to_csv(OUT_DIR / "experiment_4_leave_rule_out_summary.csv", index=False)
    detail_rows = []
    for r in all_results:
        for pr in r["per_rule"]:
            detail_rows.append({"category": r["category"], "task": r["task"], "model": r["model"], **pr})
    pd.DataFrame(detail_rows).to_csv(OUT_DIR / "experiment_4_leave_rule_out_detail.csv", index=False)

    print(f"\n{'=' * 78}\nTotal duration: {time.time() - t_start:.1f}s")
    print(f"Written: experiment_4_leave_rule_out_summary.csv, experiment_4_leave_rule_out_detail.csv")


if __name__ == "__main__":
    main()
